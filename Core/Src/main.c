/* PI and pump commands retain 0..1000 units when the PWM timer period changes. */
static uint32_t Motor_PWMCompare(uint32_t duty_per_mille)
{
    if (duty_per_mille > 1000U) duty_per_mille = 1000U;
    return duty_per_mille * (TB6612_GetPeriod() + 1U) / 1000U;
}

static void PumpControl_Task(void)
{
    static uint16_t last_pump_pwm = 0U;
    const PumpAppStatus *app;
    PumpApp_Poll(HAL_GetTick(), (uint16_t)__HAL_TIM_GET_COUNTER(&htim2),
                 HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_11) == GPIO_PIN_RESET,
                 HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_12) == GPIO_PIN_RESET);
    app = PumpApp_GetStatus();
    if ((motor_a_target != 0.0f) && (app->speed_target_rpm == 0.0f))
    {
        PID_Reset(&pid_a);
        AO_Brake();
    }
    motor_a_target = app->speed_target_rpm;
    if (app->pump_pwm != last_pump_pwm)
    {
        last_pump_pwm = app->pump_pwm;
        if (last_pump_pwm == 0U) BO_Stop();
        else BO_Control(1U, Motor_PWMCompare(last_pump_pwm));
    }
}

/**
  * @brief  A 通道速度闭环（每 SPEED_PERIOD ms 执行一次）
  * @note   PID 内部使用每周期计数，目标与遥测使用输出轴 RPM。
  *         PID 输出有符号：正数正转、负数反转
  */
static void MotorA_SpeedLoop(void)
{
    static int16_t  last_cnt  = 0;
    static uint32_t last_tick = 0;

    int16_t now;
    int32_t speed;
    float   u;
    float   target_rpm;
    float   target_counts;

    /* 未到采样周期直接返回 */
    if ((HAL_GetTick() - last_tick) < SPEED_PERIOD)
    {
        return;
    }
    last_tick = HAL_GetTick();

    /* 读编码器并算出本周期速度（16 位计数器，用 int16_t 处理溢出） */
    now      = (int16_t)__HAL_TIM_GET_COUNTER(&htim2);
    speed    = MOTOR_A_ENCODER_SIGN * (int32_t)(int16_t)(now - last_cnt);
    last_cnt = now;

    /* PID 计算，输出范围 ±1000（对应 PWM 满量程） */
    target_rpm = motor_a_target;
    /* S-curve position planner already supplies the speed reference. */
    target_counts = target_rpm / SPEED_COUNT_TO_RPM;
    if (target_rpm == 0.0f)
    {
        PID_Reset(&pid_a);
        u = 0.0f;
    }
    else
    {
        /* Extension/retraction commands must not reverse drive while braking.
         * Asymmetric limits also prevent integral windup against the zero bound. */
        u = PID_CalcWithLimits(&pid_a, target_counts, (float)speed,
                              0.0f,
                              target_rpm > 0.0f ? 0.0f : -PUMP_AXIS_MAX_PWM,
                              target_rpm > 0.0f ? PUMP_AXIS_MAX_PWM : 0.0f);
    }

    /* Position stop uses brake; otherwise signed output selects direction. */
    if (u == 0.0f)
    {
        AO_Brake();
    }
    else if (u >= 0.0f)
    {
        AO_Control(1, Motor_PWMCompare((uint32_t)u));
    }
    else
    {
        AO_Control(0, Motor_PWMCompare((uint32_t)(-u)));
    }

    BT_Control_SendTelemetry(target_rpm, (float)speed * SPEED_COUNT_TO_RPM, u);
}
